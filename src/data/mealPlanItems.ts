/** spicy: 매운맛, salty: 염도 VOC 주의, bones: 뼈·가시 주의, fried: 튀김(보온 시 눅눅함), cold: 여름 한정, brothy: 국물 있는 일품(별도 국 불필요) */
export type MenuFlag = 'spicy' | 'salty' | 'bones' | 'fried' | 'cold' | 'brothy'

export interface PlanMenuItem {
  id: string
  name: string
  slot: MealSlot
  protein: Protein
  method: CookMethod
  ingredients: string[]
  flags: MenuFlag[]
  preferred: boolean
}

type Seed = [name: string, protein: Protein, method: CookMethod, ingredients: string[], flags?: MenuFlag[], preferred?: boolean]

function build(slot: MealSlot, seeds: Seed[]): PlanMenuItem[] {
  return seeds.map(([name, protein, method, ingredients, flags = [], preferred = true], index) => ({
    id: `${slot}-${String(index + 1).padStart(3, '0')}`,
    name,
    slot,
    protein,
    method,
    ingredients,
    flags,
    preferred,
  }))
}

